#!/usr/bin/env python3
"""
scripts/lint-design-tokens.py — fail on NEW hardcoded status-color literals
in addon SCSS/CSS, enforcing the design-token consolidation.

The problem (see memory note / retest doc `ux-designsystem.md` §2.3):
across the addon tree, the same semantic role ("ok/success", "warn",
"danger/late/critical") is hardcoded as a different hex/rgb/rgba literal in
nearly every file that needs it — at least 11 distinct greens for "ok", 8
reds for "danger/late/critical", 6 ambers for "warn", spread across ~43 SCSS/
CSS files, several of them competing `--sb-*` / `$sb-cfg-*` / `$sbk-*` /
`--skj-*` / `--mc-*` namespaces that don't know about each other or about
the canonical token file. A canonical token layer landing (e.g.
`addons/southbrook_ui/static/src/scss/_sb_tokens.scss`) does nothing to
stop a 12th green appearing next week unless something greps for it. This
is that something.

WHAT COUNTS AS A VIOLATION
---------------------------
A hardcoded color literal (hex, rgb(), rgba(), hsl(), hsla()) is flagged
ONLY when it's plausibly filling a STATUS/semantic role — not every
hardcoded color in the codebase (brand/neutral colors like walnut #6b3f2a
or linen #f4ede2 are not the target and would drown the signal). "Status
role" is inferred from context: the selector, property, variable name, or
an adjacent comment on the SAME line or the PRECEDING line contains one of
the STATUS_KEYWORDS below (case-insensitive, word-ish boundaries — so
`blocked` matches but `blockquote` does not; CSS/SCSS hyphens count as
boundaries, so `.sb-late-fg` matches on `late`).

Literals that fall inside a `// ...` line comment or a `/* ... */` block
comment are never flagged themselves (they're dead code, not a live
declaration) — but comment TEXT still counts as context for a *different*,
live literal on an adjacent line (e.g. `// warn state` above a real
`background: #b35a1a;` still flags that literal).

ALLOWLIST
---------
The canonical token file(s) are exempt — defining the palette is their
job. See DESIGN_TOKEN_ALLOWLIST below. Matched by path relative to the
repo root, so it doesn't matter how the script is invoked.

BASELINE ("no NEW violations" mode)
------------------------------------
There are hundreds of pre-existing violations across the tree (see
ux-designsystem.md §2.3). A linter that fails on all of them from day one
gets `--no-verify`'d into oblivion. Default mode: load
`scripts/.design-tokens-baseline.txt` (one `path:line:value` key per
line, generated by --update-baseline), suppress anything already in it,
and fail only on violations NOT in the baseline. This lets the gate ship
today and ratchet down over time as files get migrated to tokens.

Usage:
  ./scripts/lint-design-tokens.py [PATH ...]
      Scan PATHs (files or dirs; default: addons/). Reports NEW violations
      (not in the baseline) and exits 1 if any exist, else exits 0.

  ./scripts/lint-design-tokens.py --update-baseline [PATH ...]
      Regenerate the baseline file from the current tree and exit 0.

  ./scripts/lint-design-tokens.py --all [PATH ...]
      Report every violation, including already-baselined ones (tagged
      "[baselined]"). Exit code still reflects NEW violations only.

  ./scripts/lint-design-tokens.py --baseline PATH ...
      Use an alternate baseline file instead of the default. Mainly for
      the self-test (scripts/test_lint_design_tokens.sh), which needs
      hermetic fixtures rather than the real (huge) repo baseline.

Exit:
  0  no NEW violations (baselined violations, if any, don't fail the build)
  1  at least one NEW violation
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# ─────────────────────────────────────────────────────────────────────────
# ALLOWLIST — files whose entire job is to define the palette. A hardcoded
# status-color literal here is not a bug, it's the token definition itself.
# Paths are relative to the repo root (REPO_ROOT above), POSIX-separated.
# ─────────────────────────────────────────────────────────────────────────
DESIGN_TOKEN_ALLOWLIST = frozenset({
    "addons/southbrook_ui/static/src/scss/_sb_tokens.scss",
    "addons/southbrook_estimating/static/src/scss/_southbrook_design_tokens.scss",
})

DEFAULT_BASELINE_PATH = REPO_ROOT / "scripts" / ".design-tokens-baseline.txt"

# Status/semantic keywords that turn a bare color literal into a violation.
# Case-insensitive; matched with \b so `blocked` hits but `blockquote`
# doesn't (CSS hyphens are non-word chars, so `.sb-late-fg` hits on `late`).
STATUS_KEYWORDS = (
    "ok", "success", "pass", "good",
    "warn", "warning", "caution",
    "late", "overdue",
    "danger", "error", "critical", "alert", "fail", "blocked", "block",
    "info",
)
KEYWORD_RE = re.compile(
    r"\b(?:" + "|".join(STATUS_KEYWORDS) + r")\b", re.IGNORECASE
)

# Canonical role bucket per matched keyword, used only to shape the
# suggested-token-name hint printed in the fix message. Not authoritative —
# the real token names live in the token file(s), this is just a nudge.
ROLE_CANONICAL = {
    "ok": "ok", "success": "ok", "pass": "ok", "good": "ok",
    "warn": "warn", "warning": "warn", "caution": "warn",
    "late": "danger", "overdue": "danger", "danger": "danger",
    "error": "danger", "critical": "danger", "alert": "danger",
    "fail": "danger", "blocked": "danger", "block": "danger",
    "info": "info",
}

# hex (#abc / #abcd / #aabbcc / #aabbccdd) or rgb()/rgba()/hsl()/hsla().
COLOR_RE = re.compile(
    r"#(?:[0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{4}|[0-9a-f]{3})\b"
    r"|\b(?:rgba?|hsla?)\s*\([^)]*\)",
    re.IGNORECASE,
)


def find_comment_spans(text: str):
    """Return sorted (start, end) char-offset spans in `text` that are
    `//` line comments or `/* ... */` block comments, skipping over quoted
    strings so a `//` inside `content: "http://..."` isn't mistaken for a
    comment start. Good enough for SCSS/CSS; not a full tokenizer."""
    spans = []
    i = 0
    n = len(text)
    in_string = None
    while i < n:
        c = text[i]
        if in_string:
            if c == "\\":
                i += 2
                continue
            if c == in_string:
                in_string = None
            i += 1
            continue
        if c in ("'", '"'):
            in_string = c
            i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            j = text.find("\n", i)
            end = j if j != -1 else n
            spans.append((i, end))
            i = end
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            j = text.find("*/", i + 2)
            end = j + 2 if j != -1 else n
            spans.append((i, end))
            i = end
            continue
        i += 1
    return spans


def display_path(path: Path) -> str:
    """Path relative to the repo root, POSIX-separated, stable regardless
    of how the script was invoked (absolute arg, relative arg, cwd)."""
    try:
        rel = path.resolve().relative_to(REPO_ROOT)
        return str(rel).replace("\\", "/")
    except ValueError:
        return str(path).replace("\\", "/")


def is_allowlisted(path: Path) -> bool:
    return display_path(path) in DESIGN_TOKEN_ALLOWLIST


def scan_file(path: Path):
    """Yield (lineno, value, keyword, role) for each status-context
    hardcoded color literal in `path`. Literals inside comments are never
    yielded (but comment text still supplies context for others)."""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        print(f"{path}: cannot read ({exc})", file=sys.stderr)
        return

    spans = find_comment_spans(text)

    def in_comment(offset):
        return any(s <= offset < e for s, e in spans)

    lines = text.split("\n")

    for m in COLOR_RE.finditer(text):
        start = m.start()
        if in_comment(start):
            continue
        lineno = text.count("\n", 0, start) + 1
        cur_line = lines[lineno - 1] if 0 <= lineno - 1 < len(lines) else ""
        prev_line = lines[lineno - 2] if lineno - 2 >= 0 else ""
        context = cur_line + "\n" + prev_line
        km = KEYWORD_RE.search(context)
        if not km:
            continue
        keyword = km.group(0).lower()
        role = ROLE_CANONICAL.get(keyword, keyword)
        yield (lineno, m.group(0), keyword, role)


def iter_files(targets):
    """Yield SCSS/CSS files to scan. Explicit file args are scanned as
    given (fixture-friendly); directory args are walked and filtered to
    addons/*/static/src/**/*.{scss,css}."""
    for target in targets:
        if not target.exists():
            print(f"warning: {target} does not exist", file=sys.stderr)
            continue
        if target.is_file():
            if target.suffix in (".scss", ".css"):
                yield target
        else:
            for pattern in ("*.scss", "*.css"):
                for f in sorted(target.rglob(pattern)):
                    s = str(f).replace("\\", "/")
                    if "/static/src/" in s:
                        yield f


def load_baseline(baseline_path: Path):
    if not baseline_path.exists():
        return set()
    out = set()
    for line in baseline_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            out.add(line)
    return out


def save_baseline(baseline_path: Path, keys):
    baseline_path.parent.mkdir(parents=True, exist_ok=True)
    body = "\n".join(sorted(keys))
    baseline_path.write_text(body + ("\n" if body else ""), encoding="utf-8")


def violation_key(path_str: str, lineno: int, value: str) -> str:
    return f"{path_str}:{lineno}:{value}"


def main(argv):
    args = argv[1:]
    update_baseline = False
    show_all = False
    baseline_path = DEFAULT_BASELINE_PATH
    positional = []

    i = 0
    while i < len(args):
        a = args[i]
        if a in ("-h", "--help"):
            print(__doc__)
            return 0
        elif a == "--update-baseline":
            update_baseline = True
        elif a == "--all":
            show_all = True
        elif a == "--baseline":
            i += 1
            if i >= len(args):
                print("error: --baseline requires a PATH argument", file=sys.stderr)
                return 2
            baseline_path = Path(args[i])
        else:
            positional.append(a)
        i += 1

    targets = [Path(p) for p in positional] if positional else [REPO_ROOT / "addons"]

    violations = []  # (key, path_str, lineno, value, keyword, role)
    files_seen = 0
    seen_paths = set()
    for f in iter_files(targets):
        rp = f.resolve()
        if rp in seen_paths:
            continue
        seen_paths.add(rp)
        files_seen += 1

        if is_allowlisted(f):
            continue

        path_str = display_path(f)
        for lineno, value, keyword, role in scan_file(f):
            key = violation_key(path_str, lineno, value)
            violations.append((key, path_str, lineno, value, keyword, role))

    if update_baseline:
        keys = {v[0] for v in violations}
        save_baseline(baseline_path, keys)
        print(
            f"Updated baseline: {len(keys)} known violation(s) recorded to "
            f"{baseline_path} ({files_seen} files scanned)."
        )
        return 0

    baseline = load_baseline(baseline_path)
    new_violations = [v for v in violations if v[0] not in baseline]
    baselined_violations = [v for v in violations if v[0] in baseline]

    to_report = violations if show_all else new_violations

    for key, path_str, lineno, value, keyword, role in to_report:
        tag = " [baselined]" if key in baseline else ""
        print(
            f"{path_str}:{lineno}: hardcoded color {value} used in a "
            f"'{keyword}' status context{tag}"
        )
        print(f"    fix: use var(--sb-status-{role}-fg) instead of {value}")

    if new_violations:
        print(
            f"\nFAIL: {len(new_violations)} new design-token violation(s) "
            f"not in baseline ({len(baselined_violations)} baselined, "
            f"{len(violations)} total, {files_seen} files scanned).",
            file=sys.stderr,
        )
        print(f"Baseline file: {baseline_path}", file=sys.stderr)
        print(
            "Fix the color to reference a canonical --sb-status-* token, "
            "or if this is intentional/pre-existing, run with "
            "--update-baseline to accept it.",
            file=sys.stderr,
        )
        return 1

    print(
        f"OK: no NEW design-token violations "
        f"({len(baselined_violations)} baselined violation(s) grandfathered, "
        f"{files_seen} files scanned)."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
